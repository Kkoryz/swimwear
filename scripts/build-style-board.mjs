#!/usr/bin/env node

// The style board's data (lib/style-board.mjs): every module the site's pages use, with its longest and shortest
// sample, written to src/data/style-board.json for the board page (src/pages/style-board/, a development page at
// /style-board/), and listed in docs/research/style-board/modules.md with the competitor sections each renders; a
// module none renders is listed apart (its look has no reference). site:run builds the site, shoots the board
// (design-review.mjs board) and has it reviewed module by module before any photo is made.
// Usage: node scripts/build-style-board.mjs

import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { runMain } from './lib/cli.mjs';
import { readJson, writeJson } from './lib/json-io.mjs';
import { loadSitePages } from './lib/site-pages.mjs';
import { BOARD_ROUTE, styleBoard } from './lib/style-board.mjs';

export async function buildStyleBoard({ root = process.cwd() } = {}) {
  const components = (await readJson(resolve(root, 'src/data/template-variants.json'))).components;
  const sectionModules = await readJson(resolve(root, 'docs/research/analysis/section-modules.json'), []);
  const board = styleBoard(await loadSitePages(root), components, sectionModules);
  await writeJson(resolve(root, 'src/data/style-board.json'), board);
  const row = (module) => `| ${module.key} | ${module.uses} | ${module.samples.map((sample) => `${sample.role} ${sample.words} words (${sample.route} ${sample.blockId})`).join('<br>')} | ${module.evidence.map((item) => `${item.pageType} ${item.index} ${item.module}${item.gap ? ` (GAP: ${item.gap})` : ''}`).join('<br>') || '-'} |`;
  const table = (modules) => ['| Module | Uses | Samples | Competitor sections |', '|---|---|---|---|', ...modules.map(row)];
  const backed = board.modules.filter((module) => module.evidence.length);
  const unbacked = board.modules.filter((module) => !module.evidence.length);
  const doc = [
    '# Style board',
    '',
    `Generated by \`node scripts/build-style-board.mjs\`; do not edit by hand. The board is the development page ${BOARD_ROUTE}`,
    '(shots: docs/research/style-board/board-desktop.png and board-mobile.png).',
    '',
    `## Modules no competitor section shows (${unbacked.length})`,
    '',
    'Their look has no reference: the template\'s default and what the treatment chose. The review judges them against',
    'the site\'s treatment as a whole.',
    '',
    ...(unbacked.length ? table(unbacked) : ['None.']),
    '',
    `## Modules the competitor shows (${backed.length})`,
    '',
    ...(backed.length ? table(backed) : ['None.']),
    '',
  ].join('\n');
  await mkdir(resolve(root, 'docs/research/style-board'), { recursive: true });
  await writeFile(resolve(root, 'docs/research/style-board/modules.md'), doc);
  return board;
}

runMain(import.meta.url, async () => {
  const board = await buildStyleBoard();
  console.log(`${board.modules.length} modules on the style board (${board.modules.reduce((sum, module) => sum + module.samples.length, 0)} samples)`);
  if (board.unbacked.length) console.log(`no competitor section shows: ${board.unbacked.join(', ')}`);
});
