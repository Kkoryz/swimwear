// Share of each reference core page (by section height) that the pattern library must render.
export const MIN_PATTERN_COVERAGE = 80;

const REQUIRED_FILES = [
  'astro.config.mjs',
  'site-template.json',
  'src/pages/index.astro',
  'src/layouts/BaseLayout.astro',
  'src/styles/global.css',
  'docs/research/PAGE_TOPOLOGY.md',
  'docs/research/BEHAVIORS.md',
  'docs/design-references/.gitkeep',
];

const NEXT_RESIDUE = ['next.config.js', 'next.config.mjs', 'next.config.ts', 'src/app'];

// The fonts the site ships (scripts/install-fonts.mjs, docs/research/installed-fonts.json): every role has an open or
// system family, every face its file in public/ as recorded, src/styles/fonts.css is the stylesheet the record gives
// and global.css imports it, and no other stylesheet declares a face (one place for fonts, generated by code).
export async function fontErrors(root) {
  const lock = await readJson(resolve(root, INSTALLED_FONTS), null);
  if (!lock) return [`Missing ${INSTALLED_FONTS}: run node scripts/install-fonts.mjs (site:run step "fonts")`];
  const errors = [];
  if (lock.schemaVersion !== INSTALLED_FONTS_SCHEMA) errors.push(`${INSTALLED_FONTS} schemaVersion is invalid`);
  for (const role of Object.keys(ROLE_TOKENS)) if (!lock.roles?.[role]?.family) errors.push(`${INSTALLED_FONTS} is missing role: ${role}`);
  for (const { role, family } of unlicensedRoles(lock)) errors.push(`${INSTALLED_FONTS} role ${role} uses ${family}, which is not a known open-licensed or system font; substitute a similar open font`);
  for (const face of lock.faces ?? []) {
    const file = await readFile(resolve(root, 'public', String(face.file).replace(/^\//, ''))).catch(() => null);
    if (!file) errors.push(`Missing font file public${face.file} (${face.family} ${face.weight} ${face.style}): run node scripts/install-fonts.mjs`);
    else if (createHash('sha256').update(file).digest('hex') !== face.sha256) errors.push(`Font file public${face.file} is not the one ${INSTALLED_FONTS} records: run node scripts/install-fonts.mjs`);
  }
  const text = async (path) => (await readFile(resolve(root, path), 'utf8').catch(() => null))?.replace(/\r\n/g, '\n') ?? null;
  if (await text(FONTS_CSS) !== fontsCss(lock)) errors.push(`${FONTS_CSS} is not the stylesheet ${INSTALLED_FONTS} gives (it is generated, never edited): run node scripts/install-fonts.mjs`);
  if (!(await text('src/styles/global.css'))?.includes(FONTS_IMPORT)) errors.push(`src/styles/global.css does not import fonts.css: run node scripts/install-fonts.mjs`);
  for (const path of ['src/styles/global.css', 'src/styles/reference.css']) if (hasFontFaces((await text(path)) ?? '')) errors.push(`${path} declares @font-face: the site's faces are ${FONTS_CSS}'s only (node scripts/install-fonts.mjs takes them out of reference.css)`);
  return errors;
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

// Composition axes a template may record when it deliberately departs from its reference. The default template
// follows the reference; axes are optional, but a declared axis must say what the reference and the template do.
export const COMPOSITION_AXES = ['gridGeometry', 'sectionGrouping', 'spacingRhythm', 'cardTreatment', 'ctaGrouping', 'decoration'];

// Authoring mode: a Site Factory content package rendered through an extracted design system.
async function validateAuthoringMode(root, manifest) {
  const errors = [];
  for (const file of ['src/data/authoring-pages.json', 'src/data/site-nav.json', 'src/data/template-variants.json', 'src/pages/[...slug].astro', 'docs/research/raw/reference-density.json', 'docs/research/pattern-inventory.json']) {
    if (!(await exists(resolve(root, file)))) errors.push(`Missing authoring file: ${file}`);
  }
  let pages = [];
  try {
    pages = await loadSitePages(root);
    const contractErrors = validateAuthoringPages(pages);
    errors.push(...contractErrors.map((error) => `authoring contract: ${error}`));
    if (!pages.length) errors.push('authoring mode needs at least one page');
  } catch (error) { errors.push(`Invalid authoring pages: ${error.message}`); }
  // The blog grows after launch; the manifest records the site's own pages.
  const routes = pages.filter((page) => !String(page?.pageType).startsWith('blog_')).map((page) => page.route).sort();
  const declared = [...(manifest.routes || [])].sort();
  if (JSON.stringify(routes) !== JSON.stringify(declared)) errors.push(`site-template.json routes must equal the rendered page routes: ${routes.join(', ')}`);
  try {
    const variants = await readJson(resolve(root, 'src/data/template-variants.json'));
    if (variants.schemaVersion !== 'seo-site-template-variants-v1') errors.push('template-variants.json schemaVersion is invalid');
    // A treatment name without styles would silently render unstyled; only known values are accepted.
    for (const [key, allowed] of Object.entries(TEMPLATE_VARIANTS)) {
      const value = variants.components?.[key];
      if (value != null && !allowed.includes(value)) errors.push(`template-variants.json components.${key} is ${value}; expected one of ${allowed.join(', ')}`);
    }
    // The modules named for the competitor's sections are modules the template has.
    for (const item of await readJson(resolve(root, 'docs/research/analysis/section-modules.json'), [])) {
      if (!SECTION_MODULES.includes(item.module)) errors.push(`section-modules.json names ${item.module} for ${item.pageType} #${item.index}; expected one of ${SECTION_MODULES.join(', ')}`);
    }
    for (const [part, keys] of Object.entries(BLOG_VARIANTS)) {
      for (const [key, allowed] of Object.entries(keys)) {
        const value = variants.components?.blog?.[part]?.[key];
        if (value != null && !allowed.includes(value)) errors.push(`template-variants.json components.blog.${part}.${key} is ${value}; expected one of ${allowed.join(', ')}`);
      }
    }
    for (const [pageType, value] of Object.entries(variants.components?.heroByPageType || {})) {
      if (!TEMPLATE_VARIANTS.hero.includes(value)) errors.push(`template-variants.json heroByPageType.${pageType} is ${value}; expected one of ${TEMPLATE_VARIANTS.hero.join(', ')}`);
    }
    const axes = variants.axes || {};
    for (const [axis, value] of Object.entries(axes)) {
      if (!COMPOSITION_AXES.includes(axis)) errors.push(`template-variants.json has an unknown composition axis: ${axis}`);
      if (typeof value?.source !== 'string' || typeof value?.candidate !== 'string') errors.push(`template-variants.json axis ${axis} needs source and candidate descriptions`);
    }
  } catch (error) { errors.push(`Invalid template-variants.json: ${error.message}`); }
  try {
    const patterns = await readJson(resolve(root, 'docs/research/pattern-inventory.json'));
    for (const page of patterns.pages || []) {
      for (const section of page.sections || []) if (!PATTERN_DECISIONS[section.pattern]) errors.push(`pattern-inventory.json: ${page.pageType} section ${section.index} has no library decision for pattern ${section.pattern}`);
      if (!(page.coverage >= MIN_PATTERN_COVERAGE)) errors.push(`pattern coverage for ${page.pageType} is ${page.coverage}% (minimum ${MIN_PATTERN_COVERAGE}%)`);
    }
    if (!(patterns.pages || []).length) errors.push('pattern-inventory.json lists no reference pages');
  } catch (error) { if (error.code !== 'ENOENT') errors.push(`Invalid pattern-inventory.json: ${error.message}`); }
  // A block's module attributes (data-pattern, data-variant on the grid) sit inside its .block section: a treatment
  // rule written "[data-pattern=…] .block …" never matches anything.
  const treatment = await readFile(resolve(root, 'src/styles/reference.css'), 'utf8').catch(() => '');
  for (const selector of treatment.match(/\[data-pattern="[^"]+"\]\s+\.block\b[^,{]*/g) ?? []) errors.push(`reference.css: "${selector.trim()}" never matches (a block's pattern sits inside .block: write ".block [data-pattern=…] …")`);
  return errors;
}

export async function validateTemplate(root = process.cwd()) {
  const errors = [];

  for (const file of REQUIRED_FILES) {
    if (!(await exists(resolve(root, file)))) errors.push(`Missing required file: ${file}`);
  }

  for (const file of NEXT_RESIDUE) {
    if (await exists(resolve(root, file))) errors.push(`Next.js residue is not allowed: ${file}`);
  }

  // A workspace must run the template core it recorded: a changed, missing or unrecorded core file means a hand edit
  // or a stale copy (fix: node <repo>/scripts/sync-template-core.mjs <workspace>).
  const identity = await readJson(resolve(root, 'src/data/site-identity.json'), null);
  if (identity) errors.push(...identityErrors(identity));

  const coreManifest = await readJson(resolve(root, CORE_MANIFEST), null);
  if (coreManifest) for (const { file, issue } of await coreDrift(root, coreManifest)) errors.push(`template core ${issue}: ${file}`);

  const manifestPath = resolve(root, 'site-template.json');
  if (await exists(manifestPath)) {
    try {
      if (!(await stat(manifestPath)).isFile()) throw new Error('not a file');
      const manifest = await readJson(manifestPath);
      if (manifest.schemaVersion !== 'seo-site-template-v1') {
        errors.push('site-template.json schemaVersion must be seo-site-template-v1');
      }
      try {
        const url = new URL(manifest.sourceUrl);
        if (!['http:', 'https:'].includes(url.protocol)) throw new Error('unsupported protocol');
      } catch {
        errors.push('site-template.json sourceUrl must be an absolute HTTP(S) URL');
      }
      if (typeof manifest.route !== 'string' || !manifest.route.startsWith('/')) {
        errors.push('site-template.json route must start with /');
      }
      if (!Array.isArray(manifest.components) || manifest.components.length === 0) {
        errors.push('site-template.json components must be a non-empty array');
      }
      if (!Array.isArray(manifest.islands)) errors.push('site-template.json islands must be an array');

      if (manifest.mode && !['homepage', 'navigation-shell', 'authoring'].includes(manifest.mode)) {
        errors.push('site-template.json mode must be homepage, navigation-shell or authoring');
      }

      if (manifest.mode === 'authoring') errors.push(...await validateAuthoringMode(root, manifest));

      if (manifest.mode === 'navigation-shell') {
        if (!Array.isArray(manifest.routes) || manifest.routes.length < 2) {
          errors.push('site-template.json navigation-shell routes must contain at least two routes');
        }
        for (const file of ['docs/research/navigation-shell.json', 'src/data/navigation-shell.json', 'src/pages/[...slug].astro']) {
          if (!(await exists(resolve(root, file)))) errors.push(`Missing navigation-shell file: ${file}`);
        }
        const shellPath = resolve(root, 'docs/research/navigation-shell.json');
        if (await exists(shellPath)) {
          try {
            const shell = await readJson(shellPath);
            if (shell.schemaVersion !== 'seo-site-navigation-shell-v1') errors.push('navigation-shell.json schemaVersion is invalid');
            if (!Array.isArray(shell.routes) || shell.routes.length !== shell.routeCount) errors.push('navigation-shell.json routeCount does not match routes');
            if (shell.routes?.some((route) => route.error)) errors.push('navigation-shell.json contains failed routes');
            const declared = new Set(manifest.routes || []);
            for (const route of shell.routes || []) if (!declared.has(route.route)) errors.push(`site-template.json is missing discovered route: ${route.route}`);
          } catch (error) { errors.push(`Invalid navigation-shell.json: ${error.message}`); }
        }
      }

      // The repository starter (manifest.starter) has no reference run yet; every workspace needs capture evidence.
      if (manifest.starter !== true) {
        const captureFiles = [
          'docs/design-references/desktop-1440.png',
          'docs/design-references/tablet-768.png',
          'docs/design-references/mobile-390.png',
          'docs/research/raw/capture-summary.json',
          'docs/research/raw/rendered.html',
          'docs/research/raw/font-lock.json',
          'docs/research/raw/design-lock.json',
        ];
        for (const file of captureFiles) {
          if (!(await exists(resolve(root, file)))) errors.push(`Missing real-run evidence: ${file}`);
        }
        const componentSpecs = await readdir(resolve(root, 'docs/research/components')).catch(() => []);
        if (!componentSpecs.some((file) => file.endsWith('.spec.md'))) {
          errors.push('Missing real-run evidence: docs/research/components/*.spec.md');
        }
        const fontLockPath = resolve(root, 'docs/research/raw/font-lock.json');
        if (await exists(fontLockPath)) {
          try {
            // Roles the home page does not show come from the page types' captures (lib/font-install.mjs).
            const lock = await referenceFontLock(root);
            if (lock.schemaVersion !== 'seo-site-font-lock-v1') errors.push('font-lock.json schemaVersion is invalid');
            for (const role of ['body', 'hero', 'display', 'subheading', 'navigation']) {
              if (!lock.roles?.[role]?.family) errors.push(`font-lock.json is missing role: ${role}`);
            }
          } catch (error) { errors.push(`Invalid font-lock.json: ${error.message}`); }
          // font-lock.json is what the reference uses (commercial faces included); what the site ships is the fonts step's.
          errors.push(...(await fontErrors(root)));
        }
        const designLockPath = resolve(root, 'docs/research/raw/design-lock.json');
        if (await exists(designLockPath)) {
          try {
            const lock = await readJson(designLockPath);
            if (lock.schemaVersion !== 'seo-site-design-lock-v1') errors.push('design-lock.json schemaVersion is invalid');
            const css = await readFile(resolve(root, 'src/styles/global.css'), 'utf8');
            for (const [token, expected] of Object.entries(lock.tokens || {})) {
              const match = css.match(new RegExp(`${token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*:\\s*([^;}]+)`));
              if (!match) errors.push(`global.css is missing design lock token: ${token}`);
              else if (match[1].trim().toLowerCase() !== String(expected).trim().toLowerCase()) errors.push(`global.css design token ${token} must equal ${expected}`);
            }
            for (const role of ['surfacePrimary', 'surfaceSecondary', 'surfaceDark', 'textPrimary', 'textInverse', 'border']) {
              if (!lock.roles?.[role]) errors.push(`design-lock.json is missing role: ${role}`);
            }
          } catch (error) { errors.push(`Invalid design-lock.json: ${error.message}`); }
        }
      }
    } catch (error) {
      errors.push(`Invalid site-template.json: ${error.message}`);
    }
  }

  return errors;
}

runMain(import.meta.url, async () => {
  const errors = await validateTemplate(process.cwd());
  if (errors.length) usage(errors.join('\n'));
  else console.log('Astro template contract is valid.');
}, { stack: true });
