#!/usr/bin/env node

// Lists the CSS custom properties the shared styles read with a fallback (`var(--name, default)`): the supported
// way for a template's reference.css to restyle a shared component without overriding its internal selectors; and the
// template variants with the values each takes (TemplateVariants in src/lib/types.ts), so the treatment, its repairs
// and the review always see what the template can do. Writes docs/research/CSS_HOOKS.md.
// Usage: node scripts/list-css-hooks.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { BLOCK_VARIANTS, TEMPLATE_VARIANTS } from './lib/authoring-contract.mjs';
import { runMain } from './lib/cli.mjs';

const SOURCES = ['src/styles/template.css', 'src/styles/patterns.css'];

// var(--name, fallback) uses in a declaration block; the fallback may itself contain parentheses.
function* varsWithFallback(block) {
  for (const match of block.matchAll(/var\((--[\w-]+)\s*,/g)) {
    let depth = 1;
    let index = match.index + match[0].length;
    const start = index;
    while (index < block.length && depth > 0) {
      if (block[index] === '(') depth += 1;
      if (block[index] === ')') depth -= 1;
      index += 1;
    }
    yield { name: match[1], fallback: block.slice(start, index - 1).trim() };
  }
}

export function cssHooks(css) {
  const hooks = new Map();
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const rule of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = rule[1].trim().replace(/\s+/g, ' ');
    for (const { name, fallback } of varsWithFallback(rule[2])) {
      const entry = hooks.get(name) || { name, fallback, selectors: new Set() };
      entry.selectors.add(selector);
      hooks.set(name, entry);
    }
  }
  return [...hooks.values()].sort((left, right) => left.name.localeCompare(right.name));
}

// The TemplateVariants interface of src/lib/types.ts, as written (its comments included).
export function variantsInterface(types) {
  const lines = types.split(/\r?\n/);
  const start = lines.findIndex((line) => line.startsWith('export interface TemplateVariants'));
  if (start < 0) throw new Error('no TemplateVariants in src/lib/types.ts');
  return lines.slice(start, lines.indexOf('}', start) + 1).join('\n');
}

// The document, from the template's styles and types.
export async function cssHooksDoc(root = process.cwd()) {
  const rows = [];
  for (const source of SOURCES) {
    for (const hook of cssHooks(await readFile(resolve(root, source), 'utf8'))) {
      rows.push(`| \`${hook.name}\` | \`${hook.fallback.replace(/\|/g, '\\|')}\` | ${[...hook.selectors].map((selector) => `\`${selector.replace(/\|/g, '\\|')}\``).join('<br>')} | ${source.split('/').pop()} |`);
    }
  }
  const doc = [
    '# CSS hooks for reference.css',
    '',
    'Generated by `node scripts/list-css-hooks.mjs`; do not edit by hand.',
    '',
    'A template restyles shared components by setting these custom properties (in `global.css` tokens or scoped in',
    '`reference.css`), not by overriding component-internal selectors. Design-lock tokens (`--surface-*`, `--text-*`,',
    '`--font-*`, `--size-*`, `--radius-*`, `--section-space`, ...) are set in `global.css`.',
    '',
    '| Property | Default | Read by | File |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## Template variants',
    '',
    'Set in `src/data/template-variants.json` (`components`), only with these values; a behaviour listed here is the',
    "site's to choose, not a template gap. Block patterns per page type: `docs/research/AUTHORING_INTEGRATION.md`.",
    '',
    '```ts',
    variantsInterface(await readFile(resolve(root, 'src/lib/types.ts'), 'utf8')),
    '```',
    '',
    '### The values of the string variants',
    '',
    'From the authoring contract (scripts/lib/authoring-contract.mjs). Site-wide: `components.<key>`; for one page type:',
    '`components.pageTypes.<page type>.<key>` (`splitSequence` lists split-row values in page order, cycling); for one',
    'section: `components.pageTypes.<page type>.blocks.<block id>.variant` (it wins over the variant the section came with).',
    '',
    '| Key | Site-wide values | Page-type values |',
    '|---|---|---|',
    ...[...new Set([...Object.keys(TEMPLATE_VARIANTS), ...Object.keys(BLOCK_VARIANTS)])].sort().map((key) => `| ${key === 'splitMedia' ? 'splitMedia / splitSequence' : key} | ${(TEMPLATE_VARIANTS[key] ?? []).join(', ') || '—'} | ${(BLOCK_VARIANTS[key] ?? []).join(', ') || '—'} |`),
    '',
  ].join('\n');
  return { doc, hooks: rows.length };
}

export async function writeCssHooks(root = process.cwd()) {
  const { doc, hooks } = await cssHooksDoc(root);
  await writeFile(resolve(root, 'docs/research/CSS_HOOKS.md'), doc);
  return hooks;
}

runMain(import.meta.url, async () => console.log(`${await writeCssHooks()} hooks written to docs/research/CSS_HOOKS.md`));
