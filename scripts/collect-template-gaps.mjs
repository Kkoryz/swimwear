#!/usr/bin/env node

// The template's backlog from what the sites' judgments found it cannot render (lib/template-gaps.mjs): each site's
// section modules and design reviews (the style board's included), gathered and ranked into
// docs/research/TEMPLATE_GAPS.md (and template-gaps.json). A gap with enough evidence becomes a variant or block of the
// template (made once, for every site); one without stays in the long tail, and a site renders it with the nearest
// module meanwhile. Free-text "Template gaps" in a site's notes.md are listed per site for reading, not counted.
// --hold (site:run's template-gaps step, run in the site's folder): a large layout the home or a content page's
// competitor is built from (lib/template-gaps.mjs largeLayoutGaps) waits for a person's decision in the site's
// docs/research/template-gap-decisions.json (exit 2 while one has none): made in the template, or the nearest module
// accepted. Gaps were recorded in three places and nobody acted on them.
// Usage: node scripts/collect-template-gaps.mjs <site folder>... [--hold]

import { existsSync } from 'node:fs';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import { runMain, usage } from './lib/cli.mjs';
import { readJson, writeJson } from './lib/json-io.mjs';
import { GAP_DECISIONS, HOLD_SHARE, ON_BACKLOG, largeLayoutGaps, rankGaps, siteGaps } from './lib/template-gaps.mjs';

export const DECISIONS = 'docs/research/template-gap-decisions.json';

// What one site folder holds: its section modules, its reviews, the notes' "Template gaps" lines, the competitor's
// section heights and the decisions on its large layout gaps.
export async function readSite(folder) {
  const reviewDir = resolve(folder, 'docs/research/design-review');
  const reviews = existsSync(reviewDir) ? await Promise.all((await readdir(reviewDir)).filter((name) => name.endsWith('.review.json')).map((name) => readJson(resolve(reviewDir, name)))) : [];
  const notesPath = resolve(folder, 'docs/research/analysis/notes.md');
  const notes = existsSync(notesPath) ? await readFile(notesPath, 'utf8') : '';
  const section = /^#+\s*Template gaps[^\n]*\n([\s\S]*?)(?=\n#+\s|$)/im.exec(notes)?.[1] ?? '';
  return {
    sectionModules: await readJson(resolve(folder, 'docs/research/analysis/section-modules.json'), []),
    reviews,
    notes: section.split('\n').map((line) => line.trim()).filter((line) => line.startsWith('-')),
    inventory: await readJson(resolve(folder, 'docs/research/pattern-inventory.json'), null),
    decisions: (await readJson(resolve(folder, DECISIONS), { decisions: [] })).decisions ?? [],
  };
}

export async function collectTemplateGaps(folders, { root = process.cwd() } = {}) {
  const gaps = [];
  const skipped = [];
  const notes = [];
  const large = [];
  for (const folder of folders) {
    const site = basename(resolve(folder));
    const data = await readSite(folder);
    const found = siteGaps(site, data);
    gaps.push(...found.gaps);
    skipped.push(...found.skipped);
    if (data.notes.length) notes.push({ site, lines: data.notes });
    large.push(...largeLayoutGaps(data.sectionModules, data.inventory, data.decisions).map((gap) => ({ site, ...gap })));
  }
  const ranked = rankGaps(gaps);
  const held = large.filter((gap) => !gap.decision);
  await writeJson(resolve(root, 'docs/research/template-gaps.json'), { schemaVersion: 'seo-site-template-gaps-v1', sites: folders.map((folder) => basename(resolve(folder))), onBacklog: ON_BACKLOG, ranked, skipped: skipped.map(({ site, pageType, where, reason }) => ({ site, pageType, where, reason })), holdShare: HOLD_SHARE, large });
  const table = ranked.map((row) => `| ${row.kind} | ${row.onBacklog ? 'yes' : 'no'} | ${row.sites.length} (${row.sites.join(', ')}) | ${row.pages} | ${row.blocking} | ${row.examples.map((example) => example.replace(/\|/g, '/')).join('<br>')} |`);
  const decisionRows = large.map((gap) => `| ${gap.site} | ${gap.pageType} ${gap.index} | ${gap.module} | ${Math.round(gap.share * 100)}% (${gap.height} px) | ${gap.decision ?? '**waiting**'}${gap.note ? `: ${gap.note.replace(/\|/g, '/')}` : ''} | ${gap.why.replace(/\|/g, '/')} |`);
  const skeleton = JSON.stringify({ decisions: held.map(({ pageType, index, why }) => ({ pageType, index, why, decision: GAP_DECISIONS.join(' | '), note: '' })) }, null, 2);
  const doc = [
    '# Template gaps',
    '',
    'Generated by `node scripts/collect-template-gaps.mjs <site folder>...`; do not edit by hand.',
    '',
    `What the sites' judgments found the template cannot render, by behaviour. A kind goes on the backlog when ${ON_BACKLOG.sites} sites`,
    `need it or one site needs it on ${ON_BACKLOG.pagesOnOneSite} pages; it is then made once as a variant or block of the template, never`,
    'patched into one site. "unclassified" are judgments made before gaps named their behaviour.',
    '',
    '| Kind | Backlog | Sites | Pages | P0/P1 | Examples |',
    '|---|---|---|---|---|---|',
    ...table,
    '',
    `Left out: ${skipped.length} (${['unreadable', 'missed capture'].map((reason) => `${skipped.filter((item) => item.reason === reason).length} ${reason}`).join(', ')}).`,
    '',
    '## Large layouts the template cannot render',
    '',
    `A layout gap of the competitor's home or content page taking ${Math.round(HOLD_SHARE * 100)}% of its page's height or more holds site:run until a`,
    `person decides, in the site's ${DECISIONS}: \`template\` (made in the template; the nearest module meanwhile) or`,
    '`accept` (the nearest module stays).',
    '',
    ...(large.length ? ['| Site | Section | Module now | Share of the page | Decision | Competitor section |', '|---|---|---|---|---|---|', ...decisionRows] : ['None.']),
    '',
    ...(held.length ? ['Waiting: copy into the site\'s decisions file and choose one decision each:', '', '```json', skeleton, '```', ''] : []),
    ...notes.flatMap(({ site, lines }) => [`## ${site}: notes.md "Template gaps"`, '', ...lines, '']),
  ].join('\n');
  await writeFile(resolve(root, 'docs/research/TEMPLATE_GAPS.md'), doc);
  return { ranked, skipped, large, held };
}

runMain(import.meta.url, async () => {
  const args = process.argv.slice(2).filter((arg) => arg !== '--');
  const folders = args.filter((arg) => !arg.startsWith('-'));
  if (!folders.length) return usage('Usage: node scripts/collect-template-gaps.mjs <site folder>... [--hold]');
  const { ranked, held } = await collectTemplateGaps(folders);
  console.log(ranked.map((row) => `${row.kind}: ${row.sites.length} site(s), ${row.pages} page(s)${row.onBacklog ? ', on the backlog' : ''}`).join('\n'));
  for (const gap of held) console.log(`waiting for a decision: ${gap.site} ${gap.pageType} section ${gap.index} (${Math.round(gap.share * 100)}% of the page, now ${gap.module}): ${gap.why}`);
  if (args.includes('--hold') && held.length) process.exitCode = 2;
});
